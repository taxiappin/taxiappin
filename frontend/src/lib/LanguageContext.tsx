const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const { config, updateConfig } = useConfig();
  const [currentLang, setCurrentLangState] = useState<string>(() => {
    return localStorage.getItem("taxiapp_lang") || "en";
  });
  const isEnabledFromConfig = (cfg: any): boolean => {
    if (!cfg) return true;
    if (cfg.enabledFeatures?.languages_translations === false) return false;
    if (typeof cfg.isLanguageSwitcherEnabled === 'boolean') return cfg.isLanguageSwitcherEnabled;
    return true;
  };

  const [isLanguageSwitcherEnabled, setIsLanguageSwitcherEnabledState] = useState<boolean>(() => {
    if (config) {
      return isEnabledFromConfig(config);
    }
    const saved = localStorage.getItem("taxiapp_lang_switcher_enabled");
    return saved !== null ? JSON.parse(saved) : true;
  });

  const setIsLanguageSwitcherEnabled = (enabled: boolean) => {
    setIsLanguageSwitcherEnabledState(enabled);
    localStorage.setItem('taxiapp_lang_switcher_enabled', JSON.stringify(enabled));
    updateConfig(prev => ({
      ...prev,
      isLanguageSwitcherEnabled: enabled,
      enabledFeatures: {
        ...(prev.enabledFeatures || {}),
        languages_translations: enabled
      }
    } as any));
  };

  useEffect(() => {
    if (config) {
      setIsLanguageSwitcherEnabledState(isEnabledFromConfig(config));
    }
  }, [config?.enabledFeatures?.languages_translations, (config as any)?.isLanguageSwitcherEnabled]);

  const [languageFonts, setLanguageFonts] = useState<Record<string, string>>(() => {
    const saved = localStorage.getItem('taxiapp_lang_fonts');
    if (saved) {
      try { return JSON.parse(saved); } catch (e) {}
    }
    return {
      en: 'Anek Latin',
      hi: 'Anek Devanagari',
      bn: 'Anek Bangla',
      te: 'Anek Telugu',
      mr: 'Anek Devanagari',
      ta: 'Anek Tamil',
      gu: 'Anek Gujarati',
      kn: 'Anek Kannada',
      ml: 'Anek Malayalam',
      pa: 'Anek Gurmukhi',
      or: 'Anek Odia',
      ur: 'Anek Devanagari',
    };
  });

  const setLanguageFont = (langCode: string, fontName: string) => {
    setLanguageFonts(prev => {
      const updated = { ...prev, [langCode]: fontName };
      localStorage.setItem('taxiapp_lang_fonts', JSON.stringify(updated));
      return updated;
    });
  };

  const [customTranslations, setCustomTranslations] = useState<Record<string, TranslationDictionary>>(() => {
    return (config as any)?.customTranslations || DEFAULT_TRANSLATIONS;
  });

  useEffect(() => {
    if ((config as any)?.customTranslations) {
      setCustomTranslations((config as any).customTranslations);
    }
  }, [(config as any)?.customTranslations]);

  // Dynamically load Google Font for active language
  useEffect(() => {
    const currentFontName = languageFonts[currentLang] || GOOGLE_FONTS_PER_LANG[currentLang]?.[0]?.name || 'Plus Jakarta Sans';
    const optionsList = GOOGLE_FONTS_PER_LANG[currentLang] || GOOGLE_FONTS_PER_LANG['en'];
    const fontOpt = optionsList.find(f => f.name === currentFontName) || optionsList[0];

    if (fontOpt) {
      const linkId = 'taxiapp-google-font-link';
      let link = document.getElementById(linkId) as HTMLLinkElement | null;
      if (!link) {
        link = document.createElement('link');
        link.id = linkId;
        link.rel = 'stylesheet';
        document.head.appendChild(link);
      }
      link.href = `https://fonts.googleapis.com/css2?family=${fontOpt.googleFontName}:wght@400;500;600;700;800;900&display=swap`;
      document.documentElement.style.fontFamily = fontOpt.fontFamily;
      document.body.style.fontFamily = fontOpt.fontFamily;
    }
  }, [currentLang, languageFonts]);

  const setLanguage = (langCode: string) => {
    setCurrentLangState(langCode);
    localStorage.setItem('taxiapp_lang', langCode);
  };

  const updateCustomTranslations = (newTranslations: Record<string, TranslationDictionary>) => {
    setCustomTranslations(newTranslations);
    updateConfig(prev => ({
      ...prev,
      customTranslations: newTranslations
    } as any));
  };

  const updateSingleTranslation = (langCode: string, keyOrOriginal: string, newText: string) => {
    setCustomTranslations(prev => {
      const langDict = { ...(prev[langCode] || {}) };
      langDict[keyOrOriginal] = newText;
      const normKey = normalizeStr(keyOrOriginal);
      if (normKey) langDict[normKey] = newText;
      
      const updated = { ...prev, [langCode]: langDict };
      updateConfig(p => ({ ...p, customTranslations: updated } as any));
      return updated;
    });
  };

  const normalizeStr = (str: string): string => {
    return str.toLowerCase().trim().replace(/[^a-z0-9]/g, '_').replace(/_+/g, '_').replace(/^_+|_+$/g, '');
  };

  const t = (key: string, defaultText?: string): string => {
    if (!key) return defaultText || '';

    const normKey = normalizeStr(key);
    const normDefault = defaultText ? normalizeStr(defaultText) : '';

    // IF LANGUAGE SWITCHER IS DISABLED FROM BACKEND:
    if (!isLanguageSwitcherEnabled) {
      const enCustom = customTranslations['en'] || {};
      if (enCustom[key]) return enCustom[key];
      if (normKey && enCustom[normKey]) return enCustom[normKey];
      if (defaultText && enCustom[defaultText]) return enCustom[defaultText];
      if (normDefault && enCustom[normDefault]) return enCustom[normDefault];

      const enDict = DEFAULT_TRANSLATIONS['en'] || {};
      if (enDict[key]) return enDict[key];
      if (normKey && enDict[normKey]) return enDict[normKey];
      if (defaultText && enDict[defaultText]) return enDict[defaultText];

      return defaultText || key;
    }

    const defaultLangDict = DEFAULT_TRANSLATIONS[currentLang] || {};
    const customLangDict = customTranslations[currentLang] || {};
    const langDict = { ...defaultLangDict, ...customLangDict };

    // 1. Check custom overrides for current language
    if (customTranslations[currentLang] && customTranslations[currentLang][key]) {
      return customTranslations[currentLang][key];
    }
    if (normKey && customTranslations[currentLang] && customTranslations[currentLang][normKey]) {
      return customTranslations[currentLang][normKey];
    }

    // 2. Direct key or normalized key matches in built-in dictionary
    if (langDict[key]) return langDict[key];
    if (normKey && langDict[normKey]) return langDict[normKey];

    // 3. Check defaultText in built-in dictionary
    if (defaultText && langDict[defaultText]) return langDict[defaultText];
    if (normDefault && langDict[normDefault]) return langDict[normDefault];

    // 4. Common single-word or phrase lookup dictionary fallback
    const wordDict = COMMON_WORD_TRANSLATIONS[currentLang];
    if (wordDict) {
      const lowerKey = key.toLowerCase().trim();
      const lowerDefault = defaultText ? defaultText.toLowerCase().trim() : '';
      if (wordDict[lowerKey]) return wordDict[lowerKey];
      if (wordDict[normKey]) return wordDict[normKey];
      if (lowerDefault && wordDict[lowerDefault]) return wordDict[lowerDefault];
      if (normDefault && wordDict[normDefault]) return wordDict[normDefault];
    }

    // 5. English custom translation override
    const enCustom = customTranslations['en'] || {};
    if (enCustom[key]) return enCustom[key];
    if (normKey && enCustom[normKey]) return enCustom[normKey];
    if (defaultText && enCustom[defaultText]) return enCustom[defaultText];

    // 6. English default fallback
    const enDict = DEFAULT_TRANSLATIONS['en'] || {};
    if (enDict[key]) {
      if (currentLang === 'en') return enDict[key];
      if (defaultLangDict[key]) return defaultLangDict[key];
    }

    return defaultText || key;
  };

  return (
    <LanguageContext.Provider value={{
      currentLang,
      setLanguage,
      t,
      languages: SUPPORTED_LANGUAGES,
      customTranslations,
      updateCustomTranslations,
      updateSingleTranslation,
      isLanguageSwitcherEnabled,
      setIsLanguageSwitcherEnabled,
      languageFonts,
      setLanguageFont
    }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
};
